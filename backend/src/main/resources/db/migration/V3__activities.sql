CREATE TABLE activity (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,trip_id BIGINT NOT NULL REFERENCES trip(id) ON DELETE CASCADE,
 created_by_id BIGINT NOT NULL REFERENCES app_user(id),title VARCHAR(120) NOT NULL,description VARCHAR(2000) NOT NULL,location VARCHAR(200) NOT NULL,
 date DATE NOT NULL,start_time TIME NOT NULL,estimated_cost NUMERIC(12,2) NOT NULL CHECK(estimated_cost>=0)
);
CREATE INDEX idx_activity_trip_date ON activity(trip_id,date,start_time);
