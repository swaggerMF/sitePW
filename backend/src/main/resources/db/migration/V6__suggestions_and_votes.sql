CREATE TABLE suggestion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,trip_id BIGINT NOT NULL REFERENCES trip(id) ON DELETE CASCADE,
 created_by_id BIGINT NOT NULL REFERENCES app_user(id),title VARCHAR(120) NOT NULL,description VARCHAR(2000) NOT NULL,location VARCHAR(200) NOT NULL,
 estimated_cost NUMERIC(12,2) NOT NULL CHECK(estimated_cost>=0),status VARCHAR(10) NOT NULL CHECK(status IN ('OPEN','ACCEPTED','REJECTED')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,converted BOOLEAN NOT NULL DEFAULT FALSE,activity_id BIGINT UNIQUE REFERENCES activity(id) ON DELETE SET NULL
);
CREATE TABLE vote (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,suggestion_id BIGINT NOT NULL REFERENCES suggestion(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES app_user(id),vote_value VARCHAR(4) NOT NULL CHECK(vote_value IN ('UP','DOWN')),UNIQUE(suggestion_id,user_id)
);
CREATE INDEX idx_suggestion_trip ON suggestion(trip_id);
