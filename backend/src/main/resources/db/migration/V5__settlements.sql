CREATE TABLE settlement (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,trip_id BIGINT NOT NULL REFERENCES trip(id) ON DELETE CASCADE,
 from_user_id BIGINT NOT NULL REFERENCES app_user(id),to_user_id BIGINT NOT NULL REFERENCES app_user(id),created_by_id BIGINT NOT NULL REFERENCES app_user(id),
 amount NUMERIC(12,2) NOT NULL CHECK(amount>0),date DATE NOT NULL,CHECK(from_user_id<>to_user_id)
);
CREATE INDEX idx_settlement_trip ON settlement(trip_id);
