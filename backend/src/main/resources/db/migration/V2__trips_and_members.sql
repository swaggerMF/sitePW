CREATE TABLE trip (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, destination VARCHAR(150) NOT NULL, description VARCHAR(2000) NOT NULL,
 start_date DATE NOT NULL,end_date DATE NOT NULL CHECK(end_date>=start_date),currency VARCHAR(3) NOT NULL CHECK(currency IN ('EUR','RON','USD')),
 owner_id BIGINT NOT NULL REFERENCES app_user(id),created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE trip_member (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,trip_id BIGINT NOT NULL REFERENCES trip(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES app_user(id),role VARCHAR(10) NOT NULL CHECK(role IN ('OWNER','MEMBER')),UNIQUE(trip_id,user_id)
);
CREATE INDEX idx_trip_member_user ON trip_member(user_id);
CREATE UNIQUE INDEX idx_username_lower ON app_user(lower(username));
CREATE UNIQUE INDEX idx_email_lower ON app_user(lower(email));
