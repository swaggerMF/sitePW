CREATE TABLE expense (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,trip_id BIGINT NOT NULL REFERENCES trip(id) ON DELETE CASCADE,
 created_by_id BIGINT NOT NULL REFERENCES app_user(id),paid_by_id BIGINT NOT NULL REFERENCES app_user(id),description VARCHAR(200) NOT NULL,
 amount NUMERIC(12,2) NOT NULL CHECK(amount>0),date DATE NOT NULL,created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE expense_share (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,expense_id BIGINT NOT NULL REFERENCES expense(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES app_user(id),amount NUMERIC(12,2) NOT NULL CHECK(amount>=0),UNIQUE(expense_id,user_id)
);
CREATE INDEX idx_expense_trip ON expense(trip_id);
